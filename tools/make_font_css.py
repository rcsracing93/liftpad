#!/usr/bin/env python3
"""LiftPad: write public/fonts.css, the logo font as a data URI (HANDOFF 18, C9). Python 3 standard library only.

Why: the commit gate admits no .ttf file (it names EXT_ALLOW), so the self-hosted Barlow Condensed Bold Italic (SIL Open Font License, the
license text is export/OFL-BarlowCondensed.md) is kept in git as a CSS file with the font inside. The app serves it from its own address: no Google Fonts call.
How to run:  python3 -I /abs/path/tools/make_font_css.py /abs/path/BarlowCondensed-BoldItalic.ttf /abs/path/public/fonts.css
What it changes: only the output file. Read the TTF from the google/fonts repository (ofl/barlowcondensed).
"""
import base64
import sys


def main(argv):
    if len(argv) != 3:
        print(__doc__)
        return 2
    data = open(argv[1], "rb").read()
    if data[:4] not in (b"\x00\x01\x00\x00", b"true", b"OTTO"):
        print("not a font file")
        return 1
    css = ('/* Barlow Condensed Bold Italic, SIL Open Font License 1.1 (see OFL-BarlowCondensed.txt in the public export).\n'
           '   Generated by tools/make_font_css.py. Self-hosted: the app makes no Google Fonts call for the logo. */\n'
           '@font-face{font-family:"Barlow Condensed";font-style:italic;font-weight:700;font-display:swap;'
           'src:url(data:font/ttf;base64,%s) format("truetype")}\n' % base64.b64encode(data).decode("ascii"))
    with open(argv[2], "w") as f:
        f.write(css)
    print("wrote", argv[2], len(css), "bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
