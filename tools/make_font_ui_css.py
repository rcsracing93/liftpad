#!/usr/bin/env python3
"""LiftPad: write public/fonts-ui.css, the Barlow, Barlow Semi Condensed and JetBrains Mono faces as data URIs (HANDOFF 20, E1). Python 3 standard library only.

Why: the app made three Google Fonts calls (fonts.googleapis.com, then fonts.gstatic.com). The commit gate admits no .woff2 file, so the faces are kept in git as
a CSS file with the fonts inside (same method as make_font_css.py for the logo font, C9). The licenses are export/OFL-Barlow.md, OFL-BarlowSemiCondensed.md and
OFL-JetBrainsMono.md (SIL Open Font License 1.1, copied from the npm packages).
Source: the latin woff2 files of the npm packages @fontsource/barlow, @fontsource/barlow-semi-condensed and @fontsource/jetbrains-mono, all version 5.3.0
(files/<name>-latin-<weight>-normal.woff2). The sha256 of each file is written into the CSS comment, so a second run from the same packages gives the same file.
How to run:  python3 -I /abs/path/tools/make_font_ui_css.py /abs/path/public/fonts-ui.css "Barlow|400|/abs/barlow-latin-400-normal.woff2" "Barlow|500|..." ...
  Each face is FAMILY|WEIGHT|FILE. The faces are written in the order given.
What it changes: only the output file.
"""
import base64
import hashlib
import sys

RANGE = ('U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD')


def main(argv):
    if len(argv) < 3:
        print(__doc__)
        return 2
    notes, faces = [], []
    for spec in argv[2:]:
        parts = spec.split('|')
        if len(parts) != 3 or not parts[1].isdigit():
            print('bad face (want FAMILY|WEIGHT|FILE):', spec)
            return 2
        fam, weight, path = parts
        data = open(path, 'rb').read()
        if data[:4] != b'wOF2':
            print('not a woff2 file:', path)
            return 1
        notes.append('   %s %s  %s  %s' % (fam, weight, path.rsplit('/', 1)[-1], hashlib.sha256(data).hexdigest()))
        faces.append('@font-face{font-family:"%s";font-style:normal;font-weight:%s;font-display:swap;src:url(data:font/woff2;base64,%s) format("woff2");unicode-range:%s}\n'
                     % (fam, weight, base64.b64encode(data).decode('ascii'), RANGE))
    css = ('/* Barlow, Barlow Semi Condensed and JetBrains Mono, latin subset, SIL Open Font License 1.1 (see OFL-Barlow.txt, OFL-BarlowSemiCondensed.txt and\n'
           '   OFL-JetBrainsMono.txt in the public export). From the npm packages @fontsource/barlow, @fontsource/barlow-semi-condensed and @fontsource/jetbrains-mono 5.3.0.\n'
           '   Generated by tools/make_font_ui_css.py. Self-hosted: the app makes no Google Fonts call. sha256 of each source file:\n'
           + '\n'.join(notes) + ' */\n' + ''.join(faces))
    with open(argv[1], 'w') as f:
        f.write(css)
    print('wrote', argv[1], len(css), 'bytes')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
